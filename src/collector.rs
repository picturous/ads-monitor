pub async fn collect_all(client: &Client, cfg: &AppConfig, served: bool) -> MonitorSnapshot {
    let futs = cfg.selected_platforms.iter().copied().map(|platform| {
        let client = client.clone();
        let cfg = cfg.clone();
        async move {
            match platform {
                PlatformId::OpenAi => match &cfg.openai {
                    Some(c) => openai::collect(&client, c, cfg.concurrency).await,
                    None => PlatformReport::unconfigured(
                        PlatformId::OpenAi,
                        "https://api.ads.openai.com/v1",
                        "Set OPENAI_API_KEY to enable OpenAI Ads monitoring.",
                    ),
                },
                PlatformId::Facebook => match &cfg.facebook {
                    Some(c) => {
                        facebook::collect(&client, c, cfg.lookback_days, cfg.concurrency).await
                    }
                    None => PlatformReport::unconfigured(
                        PlatformId::Facebook,
                        "https://graph.facebook.com/v25.0",
                        "Set META_ACCESS_TOKEN and META_AD_ACCOUNT_ID to enable Meta/Facebook Ads monitoring.",
                    ),
                },
                PlatformId::Google => match &cfg.google {
                    Some(c) => google::collect(&client, c, cfg.lookback_days).await,
                    None => PlatformReport::unconfigured(
                        PlatformId::Google,
                        "https://googleads.googleapis.com/v20",
                        "Set GOOGLE_ADS_CUSTOMER_ID, GOOGLE_ADS_DEVELOPER_TOKEN, and OAuth/access token to enable Google Ads monitoring.",
                    ),
                },
                PlatformId::Tiktok => match &cfg.tiktok {
                    Some(c) => tiktok::collect(&client, c, cfg.lookback_days).await,
                    None => PlatformReport::unconfigured(
                        PlatformId::Tiktok,
                        "https://business-api.tiktok.com/open_api/v1.3",
                        "Set TIKTOK_ACCESS_TOKEN and TIKTOK_ADVERTISER_ID to enable TikTok Ads monitoring.",
                    ),
                },
                PlatformId::LineOa => match &cfg.line_oa {
                    Some(c) => line_oa::collect(&client, c, cfg.concurrency).await,
                    None => PlatformReport::unconfigured(
                        PlatformId::LineOa,
                        "https://api.line.me",
                        "Set LINE_OA_CHANNEL_ID + LINE_OA_CHANNEL_SECRET (stateless) or LINE_OA_CHANNEL_ACCESS_TOKEN to enable LINE OA monitoring.",
                    ),
                },
                PlatformId::LineAds => match &cfg.line_ads {
                    Some(c) => line_ads::collect(&client, c, cfg.lookback_days).await,
                    None => PlatformReport::unconfigured(
                        PlatformId::LineAds,
                        "https://ads.line.me/api/v3",
                        "Set LINE_ADS_ACCESS_KEY, LINE_ADS_SECRET_KEY, and LINE_ADS_ACCOUNT_ID to enable LINE Ads monitoring.",
                    ),
                },
            }
        }
    });

    let platforms = join_all(futs).await;
    let summary = GlobalSummary::from_reports(&platforms);

    MonitorSnapshot {
        generated_at: Utc::now().timestamp(),
        lookback_days: cfg.lookback_days,
        served,
        demo_mode: false,
        audiences_enabled: cfg.enable_audiences,
        campaigns_enabled: cfg.enable_campaigns,
        audience_filter: cfg.audience_filter.clone(),
        cache: None,
        summary,
        platforms,
    }
}

